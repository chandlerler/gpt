'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'extension');
const previous = require(path.join(root, 'i18n-catalog.js'));
const locales = Object.fromEntries(['zh_TW', 'zh_CN', 'en'].map(language => {
  const messages = JSON.parse(fs.readFileSync(path.join(root, '_locales', language, 'messages.json'), 'utf8'));
  return [language, Object.fromEntries(Object.entries(messages).map(([key, entry]) => [key, entry.message]))];
}));
const data = { locales, legacyKeys: previous.legacyKeys.filter(key => Object.hasOwn(locales.zh_TW, key)) };
fs.writeFileSync(path.join(root, 'i18n-catalog.js'), "'use strict';\n// Generated by node tools/build-i18n.cjs.\n(function (root) {\n  const data = " + JSON.stringify(data, null, 2) + ";\n  root.DownloaderI18nCatalog = data;\n  if (typeof module !== 'undefined') module.exports = data;\n})(globalThis);\n");
